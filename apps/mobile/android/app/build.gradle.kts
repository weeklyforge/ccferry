// google-services.json is owner-provided and NEVER committed (spec §7): the
// plugin applies only when the file is present, so machines and CI runners
// without it still build a working app (push simply stays off).
val googleServicesFile = file("google-services.json")
if (googleServicesFile.exists()) {
    apply(plugin = "com.google.gms.google-services")
}

// Release signing: when android/key.properties exists (CI writes it from
// repo secrets), sign with that keystore; otherwise fall back to the debug
// key so local `flutter run --release` keeps working. Same key material on
// both paths keeps in-place self-updates possible across CI and local builds.
val keystoreProperties = java.util.Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
val hasReleaseKeystore = keystorePropertiesFile.exists()
if (hasReleaseKeystore) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}

